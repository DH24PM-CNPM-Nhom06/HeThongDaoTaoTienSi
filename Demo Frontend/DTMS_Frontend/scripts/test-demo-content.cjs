"use strict";
const fs = require("fs"), vm = require("vm"), assert = require("assert");
const path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "js/demo/sample-content.js"), "utf8");
const context = {window:{}};
vm.runInNewContext(src, context);
const samples = context.window.DTMS_SAMPLE_CONTENT;
assert.equal(samples.theses.length, 7);
assert.equal(samples.notifications.length, 8);
assert(samples.theses.every(t => t.title && t.candidate && t.field && /^\d{2}\/\d{2}\/\d{4}$/.test(t.date) && !t.fullUrl && !t.summaryUrl));
assert(samples.notifications.every(n => n.title && n.description && n.unit && n.category && /^\d{2}\/\d{2}\/\d{4}$/.test(n.date)));
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
assert(html.indexOf("js/demo/sample-content.js") < html.indexOf("js/features/notifications.js"));
assert(html.includes("data-thesis-mode-switch"));
assert(html.includes("data-notice-demo-note"));
const theses = fs.readFileSync(path.join(root, "js/features/public-theses.js"), "utf8");
const notices = fs.readFileSync(path.join(root, "js/features/notifications.js"), "utf8");
assert(theses.includes("showDemo();") && theses.includes("loadReal()"));
assert(notices.includes("global.DTMS_SAMPLE_CONTENT"));
console.log("PASS: 7 demo theses, 8 demo notices, labels and mode switch are present.");
